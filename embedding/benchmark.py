def load_embeddings(lang):
    emb_path = OUTPUT_DIR / f"embeddings_{lang}.bin"
    meta_path = OUTPUT_DIR / f"metadata_{lang}.json"

    if not emb_path.exists() or not meta_path.exists():
        return None, 0, 0, [], []

    with open(emb_path, "rb") as f:
        magic = f.read(4)
        assert magic == b"BCEF", f"Bad magic: {magic}"
        version = struct.unpack("<I", f.read(4))[0]
        count = struct.unpack("<I", f.read(4))[0]
        dim = struct.unpack("<I", f.read(4))[0]
        scale = struct.unpack("<f", f.read(4))[0]
        offset = struct.unpack("<f", f.read(4))[0]
        raw = np.frombuffer(f.read(), dtype=np.int8).reshape(count, dim)

    vectors = (raw.astype(np.float32) + 127) * scale + offset
    norms = np.linalg.norm(vectors, axis=1, keepdims=True)
    norms[norms == 0] = 1
    vectors = vectors / norms

    with open(meta_path, encoding="utf-8") as f:
        metadata = json.load(f)

    texts_path = OUTPUT_DIR / f"texts_{lang}.json"
    texts = []
    if texts_path.exists():
        with open(texts_path, encoding="utf-8") as f:
            texts = json.load(f)

    return vectors, scale, offset, metadata, texts


def tokenize(text, lang=None):
    import unicodedata
    text = unicodedata.normalize('NFKC', text.lower())
    text = ''.join(c for c in text if unicodedata.category(c) != 'Mn')
    text = text.replace('إ', 'ا').replace('أ', 'ا').replace('آ', 'ا')
    if lang == 'ru':
        text = text.replace('ё', 'е').replace('Ё', 'Е')
    if lang == 'ar':
        text = text.replace('ـ', '')
        text = text.replace('ة', 'ه')
        text = text.replace('ى', 'ي')
        text = text.replace('ؤ', 'و')
    words = set(re.findall(r'\w+', text, re.UNICODE))
    if lang == 'ar':
        ar_tokens = set()
        for t in words:
            if len(t) > 3 and t.startswith('ال'):
                t = t[2:]
            if len(t) > 3 and t.startswith('و'):
                t = t[1:]
            ar_tokens.add(t)
        words = ar_tokens
    cjk = set(re.findall(r'[぀-ゟ゠-ヿ一-鿿㐀-䶿가-힯]', text))
    if lang in ('ja', 'zh-Hans', 'zh-Hant', 'ko'):
        cjk_chars = re.findall(r'[぀-ゟ゠-ヿ一-鿿㐀-䶿가-힯]', text)
        for i in range(len(cjk_chars) - 1):
            cjk.add(cjk_chars[i] + cjk_chars[i + 1])
    return words | cjk


def lexical_score(query_tokens, text, lang=None):
    text_tokens = tokenize(text, lang=lang)
    if not query_tokens:
        return 0.0
    return len(query_tokens & text_tokens) / len(query_tokens)


def search_raw(query_vec, corpus_vecs, top_k=50):
    scores = corpus_vecs @ query_vec
    top_idx = np.argsort(scores)[::-1][:top_k]
    return [(int(i), float(scores[i])) for i in top_idx]


def search_story_collapsed(query_vec, corpus_vecs, metadata, texts, query_text, top_k=10, lexical_weight=None, lang=None):
    raw_hits = search_raw(query_vec, corpus_vecs, top_k=200)
    query_tokens = tokenize(query_text, lang=lang)
    lw = lexical_weight if lexical_weight is not None else LEXICAL_WEIGHT

    story_best = {}
    for idx, dense_score in raw_hits:
        m = metadata[idx]
        sid = m["s"]
        type_boost = TYPE_BOOSTS.get(m["t"], 0.0)
        lex_boost = 0.0
        if texts and idx < len(texts):
            lex_boost = lexical_score(query_tokens, texts[idx], lang=lang) * lw
        boosted = dense_score + type_boost + lex_boost
        if sid not in story_best or boosted > story_best[sid][1]:
            story_best[sid] = (idx, boosted)

    sorted_stories = sorted(story_best.values(), key=lambda x: x[1], reverse=True)
    return sorted_stories[:top_k]


def story_matches(story_id, accepted_story):
    return story_id == accepted_story


def matches(meta, accepted_books, accepted_stories):
    for story in accepted_stories:
        if story_matches(meta["s"], story):
            return True
    return False


def unique_stories_found(hits, metadata, accepted_stories, top_k):
    found = set()
    for idx, _ in hits[:top_k]:
        m = metadata[idx]
        for story in accepted_stories:
            if story_matches(m["s"], story):
                found.add(story)
    return found


def validate_corpus(vectors, metadata, lang):
    errors = []
    if vectors.shape[0] != len(metadata):
        errors.append(f"Shape mismatch: {vectors.shape[0]} vectors vs {len(metadata)} metadata")
    stories = [m for m in metadata if m.get("t") != "anchor"]
    anchors = [m for m in metadata if m.get("t") == "anchor"]
    if len(stories) < 1100:
        print(f"  WARNING: {lang} has only {len(stories)} stories (expected ~1189+)")
    anchor_pct = len(anchors) / len(metadata) * 100 if metadata else 0
    if anchor_pct < 5:
        print(f"  WARNING: {lang} only {anchor_pct:.1f}% anchors")
    if anchor_pct > 40:
        print(f"  WARNING: {lang} {anchor_pct:.1f}% anchors (bloat risk)")
    story_ids = [m["s"] for m in stories]
    seen = {}
    for sid in story_ids:
        seen[sid] = seen.get(sid, 0) + 1
    dupes = [s for s, c in seen.items() if c > 1]
    if dupes:
        errors.append(f"Duplicate story_ids in non-anchor entries: {dupes[:5]}")
    if errors:
        for e in errors:
            print(f"  CORPUS ERROR: {e}")
        return False
    return True


def run_benchmark(lang, embedder, queries, lexical_weight=None):
    vectors, scale, offset, metadata, texts = load_embeddings(lang)
    if vectors is None:
        print(f"  {lang}: no embeddings found, skipping")
        return None

    validate_corpus(vectors, metadata, lang)

    if not texts:
        print(f"  WARNING: texts_{lang}.json not found, lexical boost disabled")

    lw = lexical_weight if lexical_weight is not None else LEXICAL_WEIGHTS.get(lang, LEXICAL_WEIGHT)

    top1_hits = 0
    top5_hits = 0
    top1_alts = 0
    total = len(queries)
    total_coverage = 0.0
    multi_count = 0
    results = []

    for entry in queries:
        query_text, accepted_books, accepted_stories, desc = entry[:4]
        valid_alts = entry[4] if len(entry) > 4 else []

        query_prefixed = f"query: {query_text}"
        query_vec = embedder.encode_single(query_prefixed, normalize=True)

        hits = search_story_collapsed(query_vec, vectors, metadata, texts, query_text, lexical_weight=lw, lang=lang)

        top1_meta = metadata[hits[0][0]]
        top1_match = matches(top1_meta, accepted_books, accepted_stories)

        top1_is_alt = False
        if not top1_match and valid_alts:
            top1_is_alt = top1_meta["s"] in valid_alts

        top5_match = any(
            matches(metadata[idx], accepted_books, accepted_stories)
            for idx, _ in hits[:5]
        )

        found_in_5 = unique_stories_found(hits, metadata, accepted_stories, 5)
        coverage = len(found_in_5) / len(accepted_stories) if accepted_stories else 0

        if len(accepted_stories) > 1:
            total_coverage += coverage
            multi_count += 1

        if top1_match:
            top1_hits += 1
        elif top1_is_alt:
            top1_alts += 1
        if top5_match:
            top5_hits += 1

        results.append({
            "query": query_text,
            "desc": desc,
            "expected": f"{accepted_books[0]}/{accepted_stories[0]}",
            "top1": f"{top1_meta['b']}/{top1_meta['s']} (score={hits[0][1]:.4f})",
            "top1_match": top1_match,
            "top1_is_alt": top1_is_alt,
            "top5_match": top5_match,
            "top10": hits,
            "accepted_books": accepted_books,
            "accepted_stories": accepted_stories,
            "valid_alts": valid_alts,
            "coverage": coverage,
            "found_stories": sorted(found_in_5),
            "expected_stories": accepted_stories,
        })

    top1_pct = top1_hits / total * 100
    top5_pct = top5_hits / total * 100
    adj_top1_pct = (top1_hits + top1_alts) / total * 100
    avg_coverage = (total_coverage / multi_count * 100) if multi_count else 100.0
    genuinely_wrong = total - top1_hits - top1_alts

    print(f"  {lang}: top-1 = {top1_pct:.1f}% ({top1_hits}/{total}), "
          f"top-5 = {top5_pct:.1f}% ({top5_hits}/{total}), "
          f"multi-coverage = {avg_coverage:.0f}%",
          flush=True)
    if top1_alts:
        print(f"  {lang}: adjusted top-1 = {adj_top1_pct:.1f}% "
              f"({top1_alts} valid alternates, {genuinely_wrong} genuinely wrong)",
              flush=True)
    print(flush=True)

    for r in results:
        if r["top1_match"]:
            suffix = ""
            if len(r["accepted_stories"]) > 1:
                suffix = f"  [{len(r['found_stories'])}/{len(r['accepted_stories'])} parallels]"
            print(f"    HIT  query=\"{r['query']}\" -> {r['top1']}{suffix}")
            if len(r["accepted_stories"]) > 1 and r["coverage"] < 1.0:
                missing = set(r["accepted_stories"]) - set(r["found_stories"])
                print(f"         missing parallels: {', '.join(sorted(missing))}")
        elif r["top1_is_alt"]:
            marker = "  (correct in top-5)" if r["top5_match"] else ""
            print(f"    NEAR query=\"{r['query']}\" -> {r['top1']} [valid alternate]{marker}")
        else:
            marker = "  (correct in top-5)" if r["top5_match"] else ""
            print(f"    MISS query=\"{r['query']}\" -> {r['top1']}{marker}")
            for rank, (idx, score) in enumerate(r["top10"], 1):
                m = metadata[idx]
                if matches(m, r["accepted_books"], r["accepted_stories"]):
                    print(f"         correct answer at rank {rank}: {m['b']}/{m['s']} type={m['t']} (score={score:.4f})")
                    break
            else:
                print(f"         correct answer NOT in top 10")
            if len(r["accepted_stories"]) > 1:
                print(f"         found {len(r['found_stories'])}/{len(r['accepted_stories'])} parallels: {', '.join(r['found_stories']) or 'none'}")
    print(flush=True)

    return {
        "lang": lang, "top1": top1_pct, "top5": top5_pct,
        "adj_top1": adj_top1_pct, "alts": top1_alts, "wrong": genuinely_wrong,
        "coverage": avg_coverage, "results": results,
    }


def main():
    langs = sys.argv[1:] if len(sys.argv) > 1 else ["en"]

    finetuned_lora = OUTPUT_DIR / "finetuned_lora"
    finetuned = OUTPUT_DIR / "finetuned_model"
    if finetuned_lora.exists() and (finetuned_lora / "config.json").exists():
        print(f"Loading LoRA fine-tuned model: {finetuned_lora}", flush=True)
        embedder = Embedder(str(finetuned_lora))
    elif finetuned.exists() and (finetuned / "config.json").exists():
        print(f"Loading fine-tuned model: {finetuned}", flush=True)
        embedder = Embedder(str(finetuned))
    else:
        print(f"Loading base model: {MODEL_NAME}", flush=True)
        embedder = Embedder(MODEL_NAME)
    print(flush=True)

    all_results = []
    for lang in langs:
        if lang == "en":
            print(f"=== CONCEPT QUERIES ({lang}) ===", flush=True)
            result = run_benchmark(lang, embedder, QUERY_SUITE_EN)
            if result:
                all_results.append(result)

            print(f"=== VERSE RECALL ({lang}) ===", flush=True)
            vresult = run_benchmark(lang, embedder, VERSE_RECALL_EN)
            if vresult:
                vresult["lang"] = f"{lang}-verses"
                all_results.append(vresult)
        elif lang in NATIVE_QUERY_SUITES:
            print(f"=== NATIVE QUERIES ({lang}) ===", flush=True)
            result = run_benchmark(lang, embedder, NATIVE_QUERY_SUITES[lang])
            if result:
                all_results.append(result)
        else:
            print(f"=== CROSS-LINGUAL ({lang}, English queries) ===", flush=True)
            result = run_benchmark(lang, embedder, QUERY_SUITE_EN)
            if result:
                all_results.append(result)
        print(flush=True)

    if all_results:
        print("=" * 60, flush=True)
        print("SUMMARY", flush=True)
        print("=" * 60, flush=True)
        has_alts = any(r.get("alts", 0) > 0 for r in all_results)
        for r in all_results:
            status = "PASS" if r["top1"] >= 80 else "FAIL"
            cov = f", coverage = {r['coverage']:.0f}%" if r.get("coverage") else ""
            alt_info = ""
            if has_alts and r.get("alts", 0) > 0:
                alt_info = f", adj = {r['adj_top1']:.1f}% ({r['alts']} alts, {r['wrong']} wrong)"
            print(f"  {r['lang']}: top-1 = {r['top1']:.1f}%, top-5 = {r['top5']:.1f}%{cov}{alt_info} [{status}]")

        avg_top1 = sum(r["top1"] for r in all_results) / len(all_results)
        avg_top5 = sum(r["top5"] for r in all_results) / len(all_results)
        avg_adj = sum(r.get("adj_top1", r["top1"]) for r in all_results) / len(all_results)
        coverages = [r["coverage"] for r in all_results if r.get("coverage")]
        avg_cov = sum(coverages) / len(coverages) if coverages else 100.0
        print(f"\n  Average: top-1 = {avg_top1:.1f}%, top-5 = {avg_top5:.1f}%, multi-coverage = {avg_cov:.0f}%")
        if has_alts:
            print(f"  Average adjusted top-1 = {avg_adj:.1f}% (excluding valid alternates from misses)")

        hard_miss5 = []
        for r in all_results:
            for q in r["results"]:
                if not q["top5_match"] and not q.get("top1_is_alt"):
                    hard_miss5.append(f"{r['lang']}:{q['query'][:40]}")
        min_adj = min(r.get("adj_top1", r["top1"]) for r in all_results)

        gates = [
            ("avg adjusted top-1 >= 96%", avg_adj >= 96),
            ("avg top-5 >= 98%", avg_top5 >= 98),
            ("avg coverage >= 80%", avg_cov >= 80),
            (f"no language adjusted top-1 < 93% (min={min_adj:.1f}%)", min_adj >= 93),
            (f"no hard top-5 misses ({len(hard_miss5)} found)", len(hard_miss5) == 0),
        ]
        all_pass = True
        print(f"\n  Regression gates:")
        for desc, passed in gates:
            status = "PASS" if passed else "FAIL"
            if not passed:
                all_pass = False
            print(f"    [{status}] {desc}")
        if hard_miss5:
            for hm in hard_miss5[:10]:
                print(f"           {hm}")
        print(f"\n  Overall: {'PASS' if all_pass else 'FAIL'}")

    report_path = OUTPUT_DIR / "benchmark_report.json"
    with open(report_path, "w", encoding="utf-8") as f:
        json.dump(all_results, f, indent=2, ensure_ascii=False)
    print(f"\nDetailed report: {report_path}", flush=True)


